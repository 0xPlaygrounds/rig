/// A [`ToolContext`] carrying just this conversation id.
///
/// Calls made with this context thread into one remote A2A conversation. When
/// Rig's conversation memory is also in use, pass the same string to
/// [`conversation`](rig_agent::agent::AgentBuilder::conversation) so the local
/// history and the remote conversation stay aligned — the two are independent
/// and Rig does not reconcile them.
///
/// ```no_run
/// use rig_agent::completion::Prompt;
///
/// # async fn run(agent: rig_agent::agent::Agent) -> anyhow::Result<()> {
/// let reply = agent
///     .prompt("What did I ask you first?")
///     .conversation("user-42") // Rig-side memory
///     .tool_context(rig_a2a::conversation_context("user-42")) // remote A2A thread
///     .await?;
/// # let _ = reply;
/// # Ok(()) }
/// ```
pub fn conversation_context(id: impl Into<String>) -> ToolContext {
    let mut context = ToolContext::new();
    context.insert(ConversationId::new(id));
    context
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn conversation_context_carries_the_id() {
        let context = conversation_context("user-42");
        assert_eq!(
            context.get::<ConversationId>(),
            Some(&ConversationId::new("user-42"))
        );
    }
}
