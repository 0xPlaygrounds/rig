//! Agent-to-Agent (A2A) protocol client integration for the Rig agent
//! framework.
//!
//! See the [crate README](https://crates.io/crates/rig-a2a) for an overview.
//!
//! [`A2AClient`] fetches a remote agent's `AgentCard` and exposes it two ways:
//!
//! - as a **tool** on a local Rig agent, via [`A2AClient::tool`] or
//!   [`A2AAgentBuilderExt::a2a_tool`] — one remote agent becomes one tool
//!   taking a single `prompt`, the same shape
//!   [`Agent::into_tool`](rig_agent::agent::Agent::into_tool) gives a
//!   sub-agent;
//! - as a **completion model**, via [`A2AClient::model`] or
//!   [`A2AClient::agent`] — the remote agent backs a Rig [`Agent`], so
//!   `prompt`, `chat`, streaming, hooks, and conversation memory all work
//!   against it. See [`model`] for what the A2A protocol cannot carry.
//!
//! Both surfaces share one conversation store, so a [`ConversationId`] used
//! against the tool and against the model refers to the same remote
//! conversation.
//!
//! # Conversation threading
//!
//! A2A identifiers are generated by the server and echoed back by clients. Rig
//! never shows them to the model: the host records the ids issued for each
//! [`ConversationId`] and re-attaches them. Note the asymmetry — the tool and
//! model surfaces thread automatically from a conversation key, while the
//! direct [`A2AClient::message`] API stays explicit and takes ids you pass it.
//!
//! This crate currently supports native targets. Its upstream A2A client uses
//! Tokio networking, which is not available on `wasm32-unknown-unknown`.
//!
//! [`Agent`]: rig_agent::agent::Agent

