//! Regenerate, check and build the agent project, then stage the binary as
//! `bin/next`.

use std::{
    collections::BTreeSet,
    path::Path,
    process::{Command, ExitCode, Stdio},
};

use crate::{
    home::Home,
    plugins::{self, Plugin},
    project::{self, BEVY_VERSION, PACKAGE},
};

/// Why a build did not produce a binary.
pub enum Failure {
    /// A plugin pulls a different Bevy version. The text explains it.
    Conflict(String),
    /// Anything else. The text says what.
    Failed(String),
}

impl Failure {
    /// Print the failure for the user and return its exit code: 2 for a
    /// Bevy conflict, 1 otherwise.
    pub fn report(&self) -> ExitCode {
        match self {
            Self::Conflict(text) => {
                eprintln!("error: {text}");
                ExitCode::from(2)
            }
            Self::Failed(text) => {
                eprintln!("error: {text}");
                ExitCode::FAILURE
            }
        }
    }
}

/// `rig build`.
pub fn command(home: &Home) -> ExitCode {
    match build(home) {
        Ok(()) => {
            eprintln!("Staged {}", home.next().display());
            ExitCode::SUCCESS
        }
        Err(failure) => failure.report(),
    }
}

/// Whether the agent must be built before it can run: there is no binary,
/// or the project was generated by another launcher or from another
/// source.
pub fn needed(home: &Home) -> bool {
    let has_binary = home.next().is_file() || home.current().is_file();
    let source = project::rig_code_source().ok().flatten();
    !has_binary || !project::stamp_matches(&home.project(), source.as_deref())
}

/// Regenerate the project from `plugins.toml`, check its Bevy versions,
/// build it, and copy the binary to `bin/next`.
pub fn build(home: &Home) -> Result<(), Failure> {
    let failed = |what: &str, error: &dyn std::fmt::Display| {
        Failure::Failed(format!("cannot {what}: {error}"))
    };
    let plugins_file = home.plugins();
    if !plugins_file.exists() {
        std::fs::create_dir_all(&home.config)
            .and_then(|()| std::fs::write(&plugins_file, plugins::TEMPLATE))
            .map_err(|error| failed(&format!("create {}", plugins_file.display()), &error))?;
    }
    let text = std::fs::read_to_string(&plugins_file)
        .map_err(|error| failed(&format!("read {}", plugins_file.display()), &error))?;
    let plugins = plugins::parse(&plugins_file, &text).map_err(Failure::Failed)?;
    let source = project::rig_code_source().map_err(Failure::Failed)?;
    let dir = home.project();
    project::write(&dir, &plugins_file, &plugins, source.as_deref())
        .map_err(|error| failed(&format!("write {}", dir.display()), &error))?;

    check_bevy(&dir, &plugins_file, &plugins)?;
    cargo_build(&dir)?;

    let built = dir.join("target").join("debug").join(PACKAGE);
    let next = home.next();
    let staging = next.with_extension("partial");
    next.parent()
        .map_or(Ok(()), std::fs::create_dir_all)
        .and_then(|()| std::fs::copy(&built, &staging))
        .and_then(|_| std::fs::rename(&staging, &next))
        .map_err(|error| failed(&format!("stage {}", next.display()), &error))?;
    project::write_stamp(&dir, source.as_deref())
        .map_err(|error| failed("write the build stamp", &error))
}

/// Refuse a dependency graph with more than one Bevy version, naming the
/// plugins that bring the other ones.
fn check_bevy(dir: &Path, plugins_file: &Path, plugins: &[Plugin]) -> Result<(), Failure> {
    let tree = cargo_tree(dir, &[])?;
    let versions: BTreeSet<&str> = tree
        .lines()
        .filter_map(|line| line.strip_prefix("bevy_ecs v"))
        .filter_map(|rest| rest.split_whitespace().next())
        .filter(|version| *version != BEVY_VERSION)
        .collect();
    let mut problems = Vec::new();
    for version in versions {
        let users = cargo_tree(dir, &["--invert", &format!("bevy_ecs@{version}")])?;
        let culprits: Vec<&str> = plugins
            .iter()
            .map(|plugin| plugin.krate.as_str())
            .filter(|krate| {
                users.lines().any(|line| {
                    line.strip_prefix(krate)
                        .is_some_and(|rest| rest.starts_with(" v"))
                })
            })
            .collect();
        let who = if culprits.is_empty() {
            "A plugin's dependency".to_owned()
        } else {
            format!("Plugin `{}`", culprits.join("`, `"))
        };
        problems.push(format!(
            "{who} uses Bevy {version}, but rig-code uses Bevy {BEVY_VERSION}. One app \
             cannot mix two Bevy versions. Change the plugin's bevy dependency to \
             \"={BEVY_VERSION}\" or remove it from {}.",
            plugins_file.display()
        ));
    }
    if problems.is_empty() {
        Ok(())
    } else {
        Err(Failure::Conflict(problems.join("\n")))
    }
}

/// `cargo tree` of the project's normal dependencies, one package per line.
fn cargo_tree(dir: &Path, args: &[&str]) -> Result<String, Failure> {
    let output = Command::new("cargo")
        .args([
            "tree", "-e", "normal", "--prefix", "none", "--format", "{p}",
        ])
        .args(args)
        .current_dir(dir)
        .stdin(Stdio::null())
        .stderr(Stdio::inherit())
        .output()
        .map_err(|error| Failure::Failed(format!("cannot run cargo: {error}")))?;
    if !output.status.success() {
        return Err(Failure::Failed(format!(
            "cargo tree failed ({}) in {}",
            output.status,
            dir.display()
        )));
    }
    Ok(String::from_utf8_lossy(&output.stdout).into_owned())
}

/// `cargo build` with the progress bar forced on, so it also shows when
/// stderr is a pipe, and `-j RIG_JOBS` when set.
fn cargo_build(dir: &Path) -> Result<(), Failure> {
    let mut command = Command::new("cargo");
    command
        .arg("build")
        .arg("--target-dir")
        .arg(dir.join("target"))
        .current_dir(dir)
        .env("CARGO_TERM_PROGRESS_WHEN", "always")
        .env("CARGO_TERM_PROGRESS_WIDTH", "80")
        .stdin(Stdio::null());
    if let Some(jobs) = std::env::var("RIG_JOBS")
        .ok()
        .filter(|jobs| !jobs.is_empty())
    {
        let jobs: u32 = jobs
            .parse()
            .map_err(|_| Failure::Failed(format!("RIG_JOBS must be a number, not `{jobs}`")))?;
        command.arg("-j").arg(jobs.to_string());
    }
    let status = command
        .status()
        .map_err(|error| Failure::Failed(format!("cannot run cargo: {error}")))?;
    if status.success() {
        Ok(())
    } else {
        Err(Failure::Failed(format!("cargo build failed ({status})")))
    }
}
