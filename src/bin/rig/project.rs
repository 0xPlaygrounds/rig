//! The generated agent project: `Cargo.toml`, `src/main.rs` and the stamp
//! that says which launcher and rig-code source generated it.

use std::{
    collections::BTreeSet,
    path::{Path, PathBuf},
};

use crate::plugins::{Plugin, Source};

/// The one Bevy version of the agent and every plugin.
pub const BEVY_VERSION: &str = "0.20.0-rc.2";
/// The rig-code version this launcher builds when not in local-source mode.
const RIG_CODE_VERSION: &str = env!("CARGO_PKG_VERSION");
/// The package name, and so the binary name, of the agent project.
pub const PACKAGE: &str = "rig-code-bin";

/// Where rig-code comes from: a local `crates/rig-code` directory, or
/// crates.io when `None`. `RIG_SOURCE` names a repository; otherwise the
/// repository this launcher was installed from is used when it is still
/// there.
pub fn rig_code_source() -> Result<Option<PathBuf>, String> {
    if let Some(repo) = std::env::var_os("RIG_SOURCE").filter(|repo| !repo.is_empty()) {
        let dir = PathBuf::from(repo).join("crates").join("rig-code");
        if !dir.join("Cargo.toml").is_file() {
            return Err(format!(
                "RIG_SOURCE has no rig-code crate: {} is missing",
                dir.join("Cargo.toml").display()
            ));
        }
        return Ok(Some(dir));
    }
    let dir = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("crates")
        .join("rig-code");
    Ok(dir.join("Cargo.toml").is_file().then_some(dir))
}

/// The stamp of a project generated by this launcher from `source`.
pub fn stamp(source: Option<&Path>) -> String {
    let source = source.map_or_else(
        || format!("rig-code {RIG_CODE_VERSION}"),
        |dir| format!("rig-code at {}", dir.display()),
    );
    format!("rig {}\n{source}\n", env!("CARGO_PKG_VERSION"))
}

/// Write the project into `dir`. Files are rewritten only when their
/// content changes, so cargo rebuilds only for a real change.
pub fn write(
    dir: &Path,
    plugins_file: &Path,
    plugins: &[Plugin],
    source: Option<&Path>,
) -> std::io::Result<()> {
    std::fs::create_dir_all(dir.join("src"))?;
    write_if_changed(
        &dir.join("Cargo.toml"),
        &manifest(plugins_file, plugins, source),
    )?;
    write_if_changed(&dir.join("src").join("main.rs"), &main_rs(plugins))
}

/// Record that the project was built by this launcher from `source`.
pub fn write_stamp(dir: &Path, source: Option<&Path>) -> std::io::Result<()> {
    write_if_changed(&dir.join("rig.stamp"), &stamp(source))
}

/// Whether the project in `dir` was built by this launcher from `source`.
pub fn stamp_matches(dir: &Path, source: Option<&Path>) -> bool {
    std::fs::read_to_string(dir.join("rig.stamp"))
        .is_ok_and(|stamp_text| stamp_text == stamp(source))
}

fn manifest(plugins_file: &Path, plugins: &[Plugin], source: Option<&Path>) -> String {
    let features: BTreeSet<&str> = plugins
        .iter()
        .flat_map(|plugin| plugin.bevy_features.iter().map(String::as_str))
        .collect();
    let features: Vec<String> = features.into_iter().map(quote).collect();
    let rig_code = match source {
        Some(dir) => format!("{{ path = {} }}", quote(&dir.display().to_string())),
        None => quote(&format!("={RIG_CODE_VERSION}")),
    };
    let mut text = format!(
        "# Generated by rig {} from {}. Edits are overwritten.\n\
         [package]\n\
         name = \"{PACKAGE}\"\n\
         version = \"0.0.0\"\n\
         edition = \"2024\"\n\
         publish = false\n\
         \n\
         [dependencies]\n\
         bevy = {{ version = \"={BEVY_VERSION}\", default-features = false, features = [{}] }}\n\
         rig-code = {rig_code}\n",
        env!("CARGO_PKG_VERSION"),
        plugins_file.display(),
        features.join(", "),
    );
    for plugin in plugins {
        let source = match &plugin.source {
            Source::Path(path) => format!("path = {}", quote(path)),
            Source::Version(version) => format!("version = {}", quote(version)),
            Source::Git { url, reference } => {
                let mut git = format!("git = {}", quote(url));
                if let Some((kind, value)) = reference {
                    git.push_str(&format!(", {kind} = {}", quote(value)));
                }
                git
            }
        };
        text.push_str(&format!("{} = {{ {source} }}\n", plugin.krate));
    }
    if let Some(dir) = source {
        text.push_str(&format!(
            "\n[patch.crates-io]\nrig-code = {{ path = {} }}\n",
            quote(&dir.display().to_string())
        ));
    }
    text.push_str("\n[workspace]\n\n[profile.dev]\ndebug = 0\n");
    text
}

fn main_rs(plugins: &[Plugin]) -> String {
    let mut text = String::from(
        "// Generated by rig from plugins.toml. Edits are overwritten.\n\
         fn main() -> bevy::app::AppExit {\n    \
         let mut app = rig_code::app();\n",
    );
    for plugin in plugins {
        text.push_str(&format!(
            "    app.add_plugins(<{} as ::core::default::Default>::default());\n",
            plugin.plugin
        ));
    }
    text.push_str("    app.run()\n}\n");
    text
}

/// `text` as a TOML basic string.
fn quote(text: &str) -> String {
    let mut quoted = String::from('"');
    for c in text.chars() {
        match c {
            '"' => quoted.push_str("\\\""),
            '\\' => quoted.push_str("\\\\"),
            '\n' => quoted.push_str("\\n"),
            '\t' => quoted.push_str("\\t"),
            c => quoted.push(c),
        }
    }
    quoted.push('"');
    quoted
}

fn write_if_changed(path: &Path, content: &str) -> std::io::Result<()> {
    if std::fs::read_to_string(path).is_ok_and(|old| old == content) {
        return Ok(());
    }
    std::fs::write(path, content)
}
